"""Run hand-written conversations through the agent and print what it decided, turn by turn.

Purpose: QASPER questions already stand alone, so the eval cannot show `condense` at work.
This runs short follow-up chats ("... and how big is it?") and writes a readable transcript:
the standalone question, the paper vote, the decision, any clarifying question and the
cited answer. It is a showcase, not a metric.
Flow: evals/conversations/followups_demo.jsonl -> load_demo() -> converse(graph, ...) ->
Markdown (docs/m2_demo.md) via `paperlens converse`.
Params: everything under agent.* (through the graph).
Try: Add a turn that switches paper without naming it ("What about their baseline?" after
changing topic) and watch the agent stay on the old paper: that is the documented limit.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from langgraph.types import Command
from pydantic import BaseModel

from paperlens.domain import Question

MAX_CANDIDATES_SHOWN = 3


class DemoTurn(BaseModel):
    conversation_id: str
    text: str
    reply: str | None = None  # what the user answers if the agent asks "which paper?"


def load_demo(path: Path) -> list[list[DemoTurn]]:
    conversations: dict[str, list[DemoTurn]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            turn = DemoTurn.model_validate(json.loads(line))
            conversations.setdefault(turn.conversation_id, []).append(turn)
    return list(conversations.values())


def _votes(state: Mapping[str, Any], titles: Mapping[str, str]) -> str:
    shown = state.get("candidates", [])[:MAX_CANDIDATES_SHOWN]
    return ", ".join(f"{titles.get(pid, pid)} ({share:.0%})" for pid, share in shown) or "-"


def converse(graph: Any, conversations: list[list[DemoTurn]], titles: Mapping[str, str]) -> str:
    out = ["# M2 follow-up demo\n", "Generated by `paperlens converse`; one section per chat.\n"]
    for conversation in conversations:
        cid = conversation[0].conversation_id
        config = {"configurable": {"thread_id": f"demo-{cid}"}}
        out.append(f"## {cid}\n")
        for i, turn in enumerate(conversation, 1):
            # no gold paper here: the agent only sees the typed text
            question = Question(
                question_id=f"{cid}-{i}", paper_id="", question=turn.text, references=[]
            )
            state = graph.invoke({"question": question, "text": turn.text}, config)
            out.append(f"**{i}. User:** {turn.text}\n")
            if "__interrupt__" in state:
                message = state["__interrupt__"][0].value["message"]
                reply = turn.reply or ""
                out.append(f"- agent asks: {message}")
                out.append(f"- user replies: {reply or '(no reply)'}")
                state = graph.invoke(Command(resume=reply), config)
            answer = state["answer"]
            paper = titles.get(state.get("resolved_paper_id") or "", "(none)")
            out.append(f"- standalone question: {state.get('standalone', turn.text)}")
            out.append(f"- corpus vote: {_votes(state, titles)}")
            out.append(f"- decision: `{state.get('decision')}` -> {paper}")
            cited = ", ".join(answer.evidence_ids) or "-"
            out.append(f"- **answer:** {answer.text} (cited paragraphs: {cited})\n")
    return "\n".join(out)
