"""Command-line entry points (`uv run paperlens --help`).

Purpose: Thin wrappers so every action is one command and every run is driven by a YAML.
Flow: shell / Makefile -> Typer command -> config/loader.py -> the matching module.
Params: --config selects the YAML; everything else comes from it.
Try: `uv run paperlens explain-config --config experiments/configs/m1a/retr_hybrid_rrf60.yaml`
to see the fully merged config an ablation will use before you spend GPU time on it.
"""

from __future__ import annotations

from pathlib import Path
from typing import Annotated

import typer

from paperlens.config.explain import render_markdown
from paperlens.config.loader import load_config
from paperlens.config.models import AppConfig

app = typer.Typer(no_args_is_help=True, help="paperlens: agentic RAG over QASPER.")

ConfigOpt = Annotated[Path, typer.Option("--config", "-c", help="Experiment YAML.")]
DEFAULT_CONFIG = Path("experiments/configs/baseline.yaml")
DEFAULT_RESULTS = Path("evals/results")


@app.command()
def download(split: str = "validation", config: ConfigOpt = DEFAULT_CONFIG) -> None:
    """Download a QASPER split and print basic stats."""
    from paperlens.ingestion.qasper import download_split, load_split

    cfg = load_config(config)
    path = download_split(cfg.data, split)
    papers, questions = load_split(path)
    unmatched = sum(r.unmatched_evidence for q in questions for r in q.references)
    typer.echo(
        f"{split}: {len(papers)} papers, {len(questions)} questions, "
        f"{unmatched} unmatched evidence strings -> {path}"
    )


@app.command("explain-config")
def explain_config(
    config: Annotated[Path | None, typer.Option("--config", "-c")] = None,
    out: Annotated[Path | None, typer.Option("--out")] = None,
) -> None:
    """Print every parameter with its value and documentation."""
    table = render_markdown(load_config(config) if config else AppConfig())
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        header = "# Configuration reference\n\nGenerated by `make explain-config`.\n\n"
        out.write_text(header + table, encoding="utf-8")
    typer.echo(table)


@app.command()
def index(config: ConfigOpt = DEFAULT_CONFIG) -> None:
    """Build (or confirm cached) indexes for a config without running the LLM."""
    from paperlens.index.embedder import build_embedder
    from paperlens.index.store import build_or_load
    from paperlens.ingestion.qasper import download_split, load_split

    cfg = load_config(config)
    papers, _ = load_split(download_split(cfg.data, cfg.data.split))
    bundle = build_or_load(cfg, papers, build_embedder(cfg.embedding))
    typer.echo(f"chunks: {len(bundle.chunks)}, cache hit: {bundle.cache_hit}")
    bundle.dense.close()


@app.command("eval")
def eval_(config: ConfigOpt = DEFAULT_CONFIG) -> None:
    """Run one experiment and write its report."""
    from paperlens.evals.runner import run_experiment

    cfg = load_config(config)
    result = run_experiment(cfg)
    report = cfg.eval.results_dir / cfg.eval.run_name / "report.md"
    typer.echo(f"answer_f1={result.metrics.get('answer_f1', 0):.3f} report: {report}")


@app.command()
def summarize(
    results_dir: Path = DEFAULT_RESULTS,
    out: Annotated[Path | None, typer.Option("--out")] = None,
) -> None:
    """Build one table across all runs."""
    from paperlens.evals.summary import summarize as build_summary

    table = build_summary(results_dir)
    if out:
        out.write_text("# Ablation summary\n\n" + table, encoding="utf-8")
    typer.echo(table)


@app.command()
def rescore(
    results_dir: Path = DEFAULT_RESULTS,
    run: Annotated[str | None, typer.Option("--run", help="One run; default: all")] = None,
) -> None:
    """Recompute records, metrics and reports of saved runs without calling the LLM."""
    from paperlens.evals.rescore import rescore_run

    dirs = [results_dir / run] if run else sorted(d for d in results_dir.iterdir() if d.is_dir())
    # references first, so every rescored report compares against rescored numbers
    dirs.sort(key=lambda d: d.name != "baseline")
    for d in dirs:
        if (d / "records.jsonl").exists():
            result = rescore_run(d)
            typer.echo(f"{d.name}: answer_f1={result.metrics.get('answer_f1', 0):.3f}")


@app.command()
def judge(
    config: ConfigOpt = DEFAULT_CONFIG,
    results_dir: Path = DEFAULT_RESULTS,
    run: Annotated[str | None, typer.Option("--run", help="One run; default: all")] = None,
) -> None:
    """Grade saved answers with a local LLM judge (secondary metric, resumable)."""
    from paperlens.evals.judge import judge_run
    from paperlens.llm.client import OpenAICompatClient

    cfg = load_config(config)
    # fixed temperature: the same answer should get the same verdict
    llm = OpenAICompatClient(
        cfg.llm.model_copy(
            update={
                "model": cfg.judge.model,
                "extra_body": cfg.judge.extra_body,
                "temperature": 0.0,
            }
        )
    )
    dirs = [results_dir / run] if run else sorted(d for d in results_dir.iterdir() if d.is_dir())
    for d in dirs:
        if (d / "records.jsonl").exists():
            metrics = judge_run(d, cfg.judge, llm)
            typer.echo(
                f"{d.name}: judge.accuracy={metrics.get('judge.accuracy', 0):.3f} "
                f"agreement_on_exact={metrics.get('judge.agreement_on_exact', 0):.3f} "
                f"error_rate={metrics.get('judge.error_rate', 0):.3f}"
            )


@app.command()
def trace(
    config: ConfigOpt = DEFAULT_CONFIG,
    question_id: Annotated[str | None, typer.Option("--question-id", help="QASPER id")] = None,
    index: Annotated[int, typer.Option("--index", help="Position in the eval sample")] = 0,
    no_llm: Annotated[bool, typer.Option("--no-llm", help="Stop after the prompt")] = False,
    out: Annotated[Path | None, typer.Option("--out", help="Also write to this file")] = None,
) -> None:
    """Follow one question through chunks, retrieval, prompt, LLM and scoring."""
    from paperlens.trace import run_trace

    text = run_trace(load_config(config), question_id=question_id, index=index, use_llm=not no_llm)
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    typer.echo(text)


@app.command("check-gpu")
def check_gpu() -> None:
    """Verify torch sees the GPU and can run fp16."""
    from paperlens.gpu import gpu_report

    for key, value in gpu_report().items():
        typer.echo(f"{key}: {value}")
